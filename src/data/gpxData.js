export function generateGpxXml(name, waypoints) {
  const trkpts = waypoints.map(pt => `
      <trkpt lat="${pt.lat}" lon="${pt.lng}">
        <ele>${pt.ele || 0}</ele>
        <time>${new Date().toISOString()}</time>
        <name>${pt.name || ""}</name>
      </trkpt>`).join("");

  return `<?xml version="1.0" encoding="UTF-8"?>
<gpx version="1.1" creator="Bulgaria 2026 - Avihu &amp; Gil Trip App"
     xmlns="http://www.topografix.com/GPX/1/1"
     xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
     xsi:schemaLocation="http://www.topografix.com/GPX/1/1 http://www.topografix.com/GPX/1/1/gpx.xsd">
  <metadata>
    <name>${name}</name>
    <desc>Offline hiking trail for Pirin National Park, Bulgaria - October 2026</desc>
    <author><name>Avihu &amp; Gil</name></author>
    <time>${new Date().toISOString()}</time>
  </metadata>
  <trk>
    <name>${name}</name>
    <trkseg>${trkpts}
    </trkseg>
  </trk>
</gpx>`;
}

export function downloadGpxFile(filename, trackName, waypoints) {
  const xml = generateGpxXml(trackName, waypoints);
  const blob = new Blob([xml], { type: "application/gpx+xml;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
